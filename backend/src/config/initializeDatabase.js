const pool = require('./db');
const { closeExpiredAuctions } = require('../services/auctions.service');

async function initializeDatabase() {
  const client = await pool.connect();

  try {
    await client.query('BEGIN');
    await client.query(`
      ALTER TABLE auctions
        ADD COLUMN IF NOT EXISTS winner_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        ADD COLUMN IF NOT EXISTS closed_at TIMESTAMPTZ
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS auction_images (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        auction_id BIGINT NOT NULL REFERENCES auctions(id) ON DELETE CASCADE,
        image_url TEXT NOT NULL CHECK (BTRIM(image_url) <> ''),
        position INTEGER NOT NULL CHECK (position > 0),
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        UNIQUE (auction_id, position)
      )
    `);
    await client.query(`
      INSERT INTO auction_images (auction_id, image_url, position)
      SELECT id, image_url, 1 FROM auctions
      ON CONFLICT (auction_id, position) DO NOTHING
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS idx_auction_images_auction_position
      ON auction_images(auction_id, position)
    `);

    // Keep old installations usable while requiring a real image on new listings.
    await client.query(`
      UPDATE auctions
      SET image_url = '/images/producto-sin-imagen.svg'
      WHERE image_url IS NULL OR BTRIM(image_url) = ''
    `);
    await client.query(`
      UPDATE auctions AS a
      SET winner_id = (
            SELECT b.bidder_id
            FROM bids AS b
            WHERE b.auction_id = a.id
            ORDER BY b.amount DESC, b.created_at ASC, b.id ASC
            LIMIT 1
          ),
          closed_at = COALESCE(a.closed_at, a.ends_at)
      WHERE a.status = 'closed'
        AND a.winner_id IS NULL
        AND EXISTS (SELECT 1 FROM bids AS b WHERE b.auction_id = a.id)
    `);
    await client.query('ALTER TABLE auctions ALTER COLUMN image_url SET NOT NULL');

    await client.query(`
      DO $$
      BEGIN
        IF NOT EXISTS (
          SELECT 1 FROM pg_constraint
          WHERE conname = 'auctions_image_url_not_blank'
            AND conrelid = 'auctions'::regclass
        ) THEN
          ALTER TABLE auctions
            ADD CONSTRAINT auctions_image_url_not_blank
            CHECK (BTRIM(image_url) <> '');
        END IF;
      END $$
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS idx_auctions_winner
      ON auctions(winner_id) WHERE winner_id IS NOT NULL
    `);
    await client.query('COMMIT');

    await closeExpiredAuctions();
    console.log('Esquema de subastas actualizado y vencidas finalizadas.');
  } catch (error) {
    await client.query('ROLLBACK').catch(() => {});
    throw error;
  } finally {
    client.release();
  }
}

module.exports = initializeDatabase;
